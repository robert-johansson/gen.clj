(ns gen.random-test
  "Keys, splits and samplers against JAX 0.9.1 (test/fixtures/random.edn,
   generated by test/fixtures/generate.py), the published Threefry
   known-answer vectors, and distributional checks with fixed keys."
  (:refer-clojure :exclude [==])
  (:require [gen.test-support :as ts]
            [clojure.edn :as edn]
            [clojure.test :refer [deftest is testing]]
            [clojure.test.check.clojure-test :refer [defspec]]
            [clojure.test.check.generators :as gen]
            [clojure.test.check.properties :as prop]
            [gen.array :as array :refer [==]]
            [gen.random :as rng]
            [gen.random.threefry :as threefry]))

(def ^:private fixtures (edn/read-string (slurp "test/fixtures/random.edn")))

(defn- ->key [[k0 k1]] (threefry/->Key k0 k1))

(deftest threefry-known-answers
  (testing "Random123's published Threefry-2x32-20 test vectors"
    (is (= "6b20015999ba4efe" (format "%016x" (threefry/hash2x32 0 0 0 0))))
    (is (= "1cb996fcbb002be7"
           (format "%016x" (threefry/hash2x32 0xffffffff 0xffffffff 0xffffffff 0xffffffff))))
    (is (= "c4923a9c483df7a0"
           (format "%016x" (threefry/hash2x32 0x13198a2e 0x03707344 0x243f6a88 0x85a308d3))))))

(deftest keys-match-jax
  (is (true? (:partitionable fixtures)) "fixtures come from JAX's default (partitionable) mode")
  (doseq [[seed data] (:keys fixtures)]
    (is (= data (rng/key-data (rng/key seed))) (str "seed " seed)))
  (doseq [{:keys [key n out]} (:split fixtures)]
    (is (= out (mapv rng/key-data (rng/split (->key key) n)))))
  (doseq [{:keys [key data out]} (:fold-in fixtures)]
    (is (= out (rng/key-data (rng/fold-in (->key key) data))))))

(deftest bits-and-draws-match-jax
  (let [{:keys [key n out]} (:bits32 fixtures)]
    (is (= out (vec (threefry/bits32 (->key key) n)))))
  (let [{:keys [key n out]} (:bits64 fixtures)]
    (is (= (mapv #(unchecked-long (biginteger %)) out) (vec (threefry/bits64 (->key key) n)))))
  (let [{:keys [key out]} (:uniform-f32 fixtures)]
    (is (= out (array/->clj (rng/uniform (->key key) [6] {:dtype :float32})))))
  (when (ts/float64?)
    (testing "float64 draws (bit-identical uniforms; the rest to rounding)"
      (doseq [[k f tolerance] [[:uniform-f64 rng/uniform 0.0]
                               [:exponential-f64 rng/exponential 1e-15]
                               [:gumbel-f64 rng/gumbel 1e-15]
                               [:normal-f64 rng/normal 1e-15]]]
        (let [{:keys [key out]} (fixtures k)]
          (is (array/allclose? (array/array out {:dtype :float64}) (f (->key key) [6] {:dtype :float64})
                               {:rtol tolerance :atol tolerance})
              (name k)))))))

(deftest keys-are-values
  (is (= (rng/key 3) (rng/key 3)))
  (is (not= (rng/key 3) (rng/key 4)))
  (is (= "#gen/key[0 3]" (pr-str (rng/key 3))))
  (is (thrown? clojure.lang.ExceptionInfo (rng/normal [0 3]))))

(deftest draws-are-pure-functions-of-the-key
  (let [k (rng/key 11)]
    (is (= (rng/normal k) (rng/normal k)))
    (is (array/equal? (rng/normal k [5]) (rng/normal k [5])))
    (let [[k1 k2] (rng/split k)]
      (is (not= (rng/normal k1) (rng/normal k2))))
    (when (ts/jvm?) (is (instance? Double (rng/normal k)) "a 0-d draw is a host number on the JVM backend"))
    (is (= (ts/host (rng/uniform k)) (array/item (rng/uniform k [1]))) "element 0 does not depend on the shape")))

(deftest fold-in-takes-64-bit-data
  ;; DESIGN §9 (owner, 2026-10-22, the post-M5 review's P2-09). Planted,
  ;; the old fold-in, which hashed [0, d mod 2^32], fails the last two
  ;; testings here, recurse-deep-nodes-draw-afresh and
  ;; the-implicit-key-source's period
  (let [k (rng/key 1)
        [k0 k1] (rng/key-data k)
        two32 (bit-shift-left 1 32)
        words (fn [w] [(unsigned-bit-shift-right w 32) (bit-and w 0xFFFFFFFF)])]
    (testing "below 2^32, the counter [0 d]: JAX's keys"
      (doseq [d (concat (range 36) [65536 123456 (bit-shift-left 1 24) 99999999 (dec (bit-shift-left 1 31))
                                     (bit-shift-left 1 31) (dec two32)])]
        (is (= (words (threefry/hash2x32 k0 k1 0 d)) (rng/key-data (rng/fold-in k d))) (str "data " d))))
    (testing "beyond, distinct"
      (is (not= (rng/fold-in k 5) (rng/fold-in k (+ two32 5)))))
    (testing "split's key at index d, for d past 2^32 too: the counter [hi32 d, lo32 d]"
      (is (= (words (threefry/hash2x32 k0 k1 1 5)) (rng/key-data (rng/fold-in k (+ two32 5))))))))

(defspec fold-in-is-split-at-an-index 100
  (prop/for-all [seed gen/nat i (gen/choose 0 50)]
    (let [k (rng/key seed)]
      (= (rng/fold-in k i) (nth (rng/split k (inc i)) i)))))

;; Distributional checks: each uses a fixed key, so it is deterministic. The
;; bands are about five standard errors wide.

(defn- close? [actual expected band] (< (Math/abs (- (ts/number actual) (ts/number expected))) band))

(deftest sampler-moments
  (let [k (rng/key 2026) n 200000]
    (testing "normal"
      (let [x (rng/normal k [n])]
        (is (close? (array/mean x) 0.0 0.012))
        (is (close? (array/variance x) 1.0 0.016))))
    (testing "exponential: mean 1, variance 1"
      (let [x (rng/exponential k [n])]
        (is (close? (array/mean x) 1.0 0.012))
        (is (close? (array/variance x) 1.0 0.04))))
    (testing "gumbel: mean γ, variance π²/6"
      (let [x (rng/gumbel k [n])]
        (is (close? (array/mean x) 0.5772156649 0.015))
        (is (close? (array/variance x) (/ (* Math/PI Math/PI) 6) 0.05))))
    (testing "bernoulli and its bool dtype"
      (let [x (rng/bernoulli k 0.3 [n])]
        (is (= :bool (array/dtype x)))
        (is (close? (array/mean x) 0.3 0.006))))
    (testing "categorical frequencies"
      (let [x (rng/categorical k (array/log (array/array [0.2 0.5 0.3])) [n])
            freqs (array/->clj (array/mean (== (array/expand-dims x -1) (array/arange 3)) {:axis 0}))]
        (is (every? true? (map #(close? %1 %2 0.006) freqs [0.2 0.5 0.3])))))
    (testing "categorical with batched logits draws per row"
      (let [logits (array/log (array/array [[0.999 0.001] [0.001 0.999]]))
            x (rng/categorical k logits)]
        (is (= [2] (array/shape x)))
        (is (= [0 1] (array/->clj x)))))
    (testing "gamma: mean α, variance α (with the α < 1 boost)"
      (doseq [alpha [0.3 1.0 2.5 9.0]]
        (let [x (rng/gamma k (array/full [n] alpha))]
          (is (close? (array/mean x) alpha (* 5 (Math/sqrt (/ alpha n)))) (str "mean, alpha " alpha))
          (is (close? (array/variance x) alpha (* 0.05 alpha 4)) (str "variance, alpha " alpha))
          (is (pos? (ts/number (array/min x))) (str "positive, alpha " alpha)))))
    (testing "randint covers [low, high) uniformly"
      (let [x (rng/randint k 2 5 [n])]
        (is (= (ts/int-dtype) (array/dtype x)))
        (is (= 2 (ts/host (array/min x))))
        (is (= 4 (ts/host (array/max x))))
        (is (close? (array/mean x) 3.0 0.01))))))
