(def ^:private fixtures (edn/read-string (slurp "test/fixtures/random.edn")))

(defn- ->key [[k0 k1]] (threefry/->Key k0 k1))

(deftest threefry-known-answers
  (testing "Random123's published Threefry-2x32-20 test vectors"
    (is (= "6b20015999ba4efe" (format "%016x" (threefry/hash2x32 0 0 0 0))))
    (is (= "1cb996fcbb002be7"
           (format "%016x" (threefry/hash2x32 0xffffffff 0xffffffff 0xffffffff 0xffffffff))))
    (is (= "c4923a9c483df7a0"
           (format "%016x" (threefry/hash2x32 0x13198a2e 0x03707344 0x243f6a88 0x85a308d3))))))

(deftest keys-match-jax
  (is (true? (:partitionable fixtures)) "fixtures come from JAX's default (partitionable) mode")
  (doseq [[seed data] (:keys fixtures)]
    (is (= data (rng/key-data (rng/key seed))) (str "seed " seed)))
  (doseq [{:keys [key n out]} (:split fixtures)]
    (is (= out (mapv rng/key-data (rng/split (->key key) n)))))
  (doseq [{:keys [key data out]} (:fold-in fixtures)]
    (is (= out (rng/key-data (rng/fold-in (->key key) data))))))

(deftest bits-and-draws-match-jax
  (let [{:keys [key n out]} (:bits32 fixtures)]
    (is (= out (vec (threefry/bits32 (->key key) n)))))
  (let [{:keys [key n out]} (:bits64 fixtures)]
    (is (= (mapv #(unchecked-long (biginteger %)) out) (vec (threefry/bits64 (->key key) n)))))
  (let [{:keys [key out]} (:uniform-f32 fixtures)]
    (is (= out (array/->clj (rng/uniform (->key key) [6] {:dtype :float32})))))
  (when (ts/float64?)
    (testing "float64 draws (bit-identical uniforms; the rest to rounding)"
      (doseq [[k f tolerance] [[:uniform-f64 rng/uniform 0.0]
                               [:exponential-f64 rng/exponential 1e-15]
                               [:gumbel-f64 rng/gumbel 1e-15]
                               [:normal-f64 rng/normal 1e-15]]]
        (let [{:keys [key out]} (fixtures k)]
          (is (array/allclose? (array/array out {:dtype :float64}) (f (->key key) [6] {:dtype :float64})
                               {:rtol tolerance :atol tolerance})
              (name k)))))))

(deftest keys-are-values
  (is (= (rng/key 3) (rng/key 3)))
  (is (not= (rng/key 3) (rng/key 4)))
  (is (= "#gen/key[0 3]" (pr-str (rng/key 3))))
  (is (thrown? clojure.lang.ExceptionInfo (rng/normal [0 3]))))

(deftest draws-are-pure-functions-of-the-key
  (let [k (rng/key 11)]
    (is (= (rng/normal k) (rng/normal k)))
    (is (array/equal? (rng/normal k [5]) (rng/normal k [5])))
    (let [[k1 k2] (rng/split k)]
      (is (not= (rng/normal k1) (rng/normal k2))))
    (when (ts/jvm?) (is (instance? Double (rng/normal k)) "a 0-d draw is a host number on the JVM backend"))
    (is (= (ts/host (rng/uniform k)) (array/item (rng/uniform k [1]))) "element 0 does not depend on the shape")))

(deftest fold-in-takes-64-bit-data
  ;; DESIGN §9 (owner, 2026-10-22, the post-M5 review's P2-09). Planted,
  ;; the old fold-in, which hashed [0, d mod 2^32], fails the last two
  ;; testings here, recurse-deep-nodes-draw-afresh and
  ;; the-implicit-key-source's period
  (let [k (rng/key 1)
        [k0 k1] (rng/key-data k)
        two32 (bit-shift-left 1 32)
        words (fn [w] [(unsigned-bit-shift-right w 32) (bit-and w 0xFFFFFFFF)])]
    (testing "below 2^32, the counter [0 d]: JAX's keys"
      (doseq [d (concat (range 36) [65536 123456 (bit-shift-left 1 24) 99999999 (dec (bit-shift-left 1 31))
                                     (bit-shift-left 1 31) (dec two32)])]
        (is (= (words (threefry/hash2x32 k0 k1 0 d)) (rng/key-data (rng/fold-in k d))) (str "data " d))))
    (testing "beyond, distinct"
      (is (not= (rng/fold-in k 5) (rng/fold-in k (+ two32 5)))))
    (testing "split's key at index d, for d past 2^32 too: the counter [hi32 d, lo32 d]"
      (is (= (words (threefry/hash2x32 k0 k1 1 5)) (rng/key-data (rng/fold-in k (+ two32 5))))))
    (testing "data that is no non-negative integer is loud"
      ;; the cross-review of genclj-vh7n: the old mask wrapped a negative as
      ;; JAX's uint32 does, the 64-bit counter does not, and a long cast took
      ;; 2.5 for 2 (DESIGN §9); plants: no check gives keys for all three, the
      ;; sign check alone for 2.5 and 3.0
      ;; and past Long/MAX_VALUE, where the long cast threw a raw
      ;; IllegalArgumentException (cross-review 4); plant: the bound alone
      ;; missing lets 2^63 through to it
      (doseq [d [-1 2.5 3.0 (bigint (Math/pow 2 63))]]
        (is (= :invalid-data (:reason (ex-data (try (rng/fold-in k d) nil (catch clojure.lang.ExceptionInfo e e)))))
            (pr-str d)))
      (is (= (rng/fold-in k Long/MAX_VALUE) (rng/fold-in k (bigint Long/MAX_VALUE))) "up to Long/MAX_VALUE")
      (is (= (rng/fold-in k 3) (rng/fold-in k (int 3)) (rng/fold-in k (bigint 3))) "any integer type"))))

(defspec fold-in-is-split-at-an-index 100
  (prop/for-all [seed laws/seeds i (gen/choose 0 50)]
    (let [k (rng/key seed)]
      (= (rng/fold-in k i) (nth (rng/split k (inc i)) i)))))

;; Distributional checks: each uses a fixed key, so it is deterministic. The
;; bands are about five standard errors wide.

(defn- close? [actual expected band] (< (Math/abs (- (ts/number actual) (ts/number expected))) band))

(deftest the-first-accepted-proposal-wins
  ;; genclj-khnp (I3-09): gamma's fold and gen.dist's Poisson and binomial
  ;; one, written twice, are rng/first-accepted; elementwise, the fallback
  ;; where no round accepts (planted: the fold in order, the last accepted)
  (is (= 2.0 (rng/first-accepted 0.0 [[false 1.0] [true 2.0] [true 3.0]])))
  (is (= 0.0 (rng/first-accepted 0.0 [[false 1.0] [false 2.0]])))
  (is (= [2.0 1.0 0.0] (ts/host (rng/first-accepted (array/zeros [3]) [[(array/array [false true false]) (array/full [3] 1.0)]
                                                                       [(array/array [true true false]) (array/full [3] 2.0)]])))))

(deftest sampler-moments
  (let [k (rng/key 2026) n 200000]
    (testing "normal"
      (let [x (rng/normal k [n])]
        (is (close? (array/mean x) 0.0 0.012))
        (is (close? (array/variance x) 1.0 0.016))))
    (testing "exponential: mean 1, variance 1"
      (let [x (rng/exponential k [n])]
        (is (close? (array/mean x) 1.0 0.012))
        (is (close? (array/variance x) 1.0 0.04))))
    (testing "gumbel: mean γ, variance π²/6"
      (let [x (rng/gumbel k [n])]
        (is (close? (array/mean x) 0.5772156649 0.015))
        (is (close? (array/variance x) (/ (* Math/PI Math/PI) 6) 0.05))))
    (testing "bernoulli and its bool dtype"
      (let [x (rng/bernoulli k 0.3 [n])]
        (is (= :bool (array/dtype x)))
        (is (close? (array/mean x) 0.3 0.006))))
    (testing "categorical frequencies"
      (let [x (rng/categorical k (array/log (array/array [0.2 0.5 0.3])) [n])
            freqs (array/->clj (array/mean (== (array/expand-dims x -1) (array/arange 3)) {:axis 0}))]
        (is (every? true? (map #(close? %1 %2 0.006) freqs [0.2 0.5 0.3])))))
    (testing "categorical with batched logits draws per row"
      (let [logits (array/log (array/array [[0.999 0.001] [0.001 0.999]]))
            x (rng/categorical k logits)]
        (is (= [2] (array/shape x)))
        (is (= [0 1] (array/->clj x)))))
    (testing "gamma: mean α, variance α (with the α < 1 boost)"
      (doseq [alpha [0.3 1.0 2.5 9.0]]
        (let [x (rng/gamma k (array/full [n] alpha))]
          (is (close? (array/mean x) alpha (* 5 (Math/sqrt (/ alpha n)))) (str "mean, alpha " alpha))
          (is (close? (array/variance x) alpha (* 0.05 alpha 4)) (str "variance, alpha " alpha))
          (is (pos? (ts/number (array/min x))) (str "positive, alpha " alpha)))))
    (testing "randint covers [low, high) uniformly"
      (let [x (rng/randint k 2 5 [n])]
        (is (= (ts/int-dtype) (array/dtype x)))
        (is (= 2 (ts/host (array/min x))))
        (is (= 4 (ts/host (array/max x))))
        (is (close? (array/mean x) 3.0 0.01))))))

(defn- reason [f] (:reason (try (f) nil (catch clojure.lang.ExceptionInfo e (ex-data e)))))

(deftest randint-stays-inside-its-range
  ;; genclj-psgi: floor(low + u·(high - low)) in the backend's default
  ;; float rounded up to high: in float32 for about 0.3% of the draws at
  ;; low 1e6, high 1e6 + 10 (MLX's draws held 1000010), and in float64 for
  ;; ranges far from 0 or for the largest uniform; uniform-discrete sampled
  ;; outside its support. Now integer arithmetic on the uniforms' bits
  (testing "low 1e6, high 1e6 + 10, many keys: every value inside, each a tenth within 5 standard errors"
    (let [n 100000
          counts (frequencies (ts/host (rng/randint (rng/key 1) 1000000 1000010 [n])))]
      (is (= (set (range 1000000 1000010)) (set (keys counts))))
      (is (every? #(< (Math/abs (- (double %) 10000.0)) (* 5 (Math/sqrt (* n 0.1 0.9)))) (vals counts)) (pr-str counts))))
  (testing "the largest uniform gives high - 1 and the smallest low, also far from 0"
    ;; the largest of the dtype asked: float64's gave high at low 1e6 too
    (with-redefs [rng/uniform (fn [_ shape {:keys [dtype]}]
                                (array/full shape (- 1.0 (Math/pow 2.0 (if (= :float64 dtype) -52 -23))) {:dtype dtype}))]
      (is (= [1000009 1000009] (ts/host (rng/randint (rng/key 0) 1000000 1000010 [2]))))
      (is (= [4 4] (ts/host (rng/randint (rng/key 0) 2 5 [2]))))
      (when (= :int64 (ts/int-dtype))
        (is (= 4503599627370505 (ts/host (rng/randint (rng/key 0) 4503599627370496 4503599627370506)))
            "at 2^52, where float64's floor(low + u·r) is high")))
    (with-redefs [rng/uniform (fn [_ shape {:keys [dtype]}] (array/zeros shape {:dtype dtype}))]
      (is (= [1000000 1000000] (ts/host (rng/randint (rng/key 0) 1000000 1000010 [2]))))))
  (testing "array bounds, broadcast"
    (let [x (ts/host (rng/randint (rng/key 4) (array/array [0 100 -7]) (array/array [1 103 -6]) [1000 3]))]
      (is (= #{[0 100 -7] [0 101 -7] [0 102 -7]} (set x)))))
  (testing "an empty range and a fractional bound are loud"
    (is (= :empty-range (reason #(rng/randint (rng/key 0) 5 5))))
    (is (= :empty-range (reason #(rng/randint (rng/key 0) 5 2 [3]))))
    (is (= :invalid-args (reason #(rng/randint (rng/key 0) 0 2.5))))
    (when (ts/jvm?)
      (is (= :empty-range (reason #(rng/randint (rng/key 0) (array/array [0 3]) (array/array [1 3])))) "read when concrete")))
  (testing "past int32, on a backend whose int is int32, loud (it wrapped)"
    (when (= :int32 (ts/int-dtype))
      (is (= :invalid-args (reason #(rng/randint (rng/key 0) 0 3000000000)))))))

(defspec randint-is-exact 100
  ;; the arithmetic of genclj-psgi's randint: the draw is low + floor(k·r /
  ;; 2^b), checked against BigInts, for host and array bounds, up to r =
  ;; 2^53 (the JVM backend's exact ints). In float64 k is one uniform's 52
  ;; bits (b = 52); in float32 three uniforms' 23 bits each, the first drawn
  ;; lowest (b = 69). Planted (2026-11-06): a term dropped from a column
  ;; (d2·r1), or the carry into the result's column, fails it (the lowest
  ;; carry moves a draw with probability about 2^-23: no test sees it)
  (prop/for-all [ds (gen/vector (gen/choose 0 8388607) 3)
                 k52 (gen/fmap (fn [[a b]] (+ (* a 67108864) b)) (gen/tuple (gen/choose 0 67108863) (gen/choose 0 67108863)))
                 r (gen/one-of [(gen/choose 1 10) (gen/choose 1 Integer/MAX_VALUE)
                                (gen/fmap #(inc (long (* % 9007199254740991))) (gen/double* {:min 0.0 :max 1.0 :NaN? false}))
                                (gen/fmap #(bit-shift-left 1 %) (gen/choose 0 52))])
                 lo (gen/choose -500 500)
                 arrays? gen/boolean]
    (let [r (long (if (= :int32 (ts/int-dtype)) (min r 2147483147) r))
          f64? (= :float64 (ts/float-dtype))
          calls (atom 0)
          got (with-redefs [rng/uniform (fn [_ shape {:keys [dtype]}]
                                          (let [i @calls]
                                            (swap! calls inc)
                                            (array/full shape (if f64? (/ (double k52) 4503599627370496.0) (/ (double (ds i)) 8388608.0))
                                                        {:dtype dtype})))]
                (ts/host (if arrays?
                           (rng/randint (rng/key 0) (array/array [lo lo]) (array/array [(+ lo r) (+ lo r)]) [2])
                           (rng/randint (rng/key 0) lo (+ lo r) [2]))))
          [d0 d1 d2] ds
          want (if f64?
                 (+ lo (long (quot (* (bigint k52) (bigint r)) 4503599627370496N)))
                 (let [k (+ (* (bigint d2) 70368744177664N) (* (bigint d1) 8388608N) (bigint d0))]
                   (+ lo (long (quot (* k (bigint r)) 590295810358705651712N)))))]
      (and (= (if f64? 1 3) @calls) (= [want want] got)))))

(deftest keys-take-64-bit-integer-seeds
