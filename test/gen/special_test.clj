(ns gen.special-test
  "Special functions against scipy.special reference values, and the
   inverse trigonometric and hyperbolic functions against numpy's
   (test/fixtures/special.edn, generated by test/fixtures/generate.py)."
  (:require [clojure.edn :as edn]
            [gen.test-support :as ts]
            [clojure.test :refer [deftest is testing]]
            [gen.array :as array]))

(def ^:private fixtures (edn/read-string (slurp "test/fixtures/special.edn")))

(defn- error
  "Absolute error for |expected| < 1, relative otherwise; none when both
   are NaN."
  [actual expected]
  (if (or (== actual expected) (and (Double/isNaN actual) (Double/isNaN expected)))
    0.0
    (/ (Math/abs (- (double actual) (double expected))) (max 1.0 (Math/abs (double expected))))))

(defn- check [k f tolerance]
  (doseq [[x expected] (fixtures k)]
    (is (<= (error (f x) expected) tolerance) (str (name k) " at " x))))

(deftest against-scipy
  (testing "host scalars"
    (check :erf array/erf 1e-15)
    (check :erfinv array/erfinv 1e-15)
    (check :lgamma array/lgamma 1e-14)
    (check :digamma array/digamma 1e-14))
  (testing "arrays give the host values: exactly on the JVM backend, within a few ulps on others"
    (doseq [[k f] [[:erf array/erf] [:erfinv array/erfinv] [:lgamma array/lgamma] [:digamma array/digamma]]]
      (let [xs (mapv first (fixtures k))]
        (if (ts/jvm?)
          (is (= (mapv f xs) (array/->clj (f (array/array xs)))) (name k))
          ;; on float32, against the host at the rounded inputs (near ±1 and
          ;; the poles, the rounding of the input alone moves the value)
          (let [xs32 (if (ts/f32?) (mapv #(double (float %)) xs) xs)]
            (is (ts/close? (array/array (mapv f xs32) {:dtype (ts/float-dtype)}) (f (array/array xs))
                           (if (ts/f32?) {:rtol 1e-4 :atol 1e-5} {:rtol 1e-13 :atol 1e-13}))
                (name k))))))))

(def ^:private elementary
  "The unary functions numpy's values check, by fixture key."
  {:asin array/asin :acos array/acos :atan array/atan :sinh array/sinh :cosh array/cosh})

(defn- bits
  "x's IEEE bits: the same for every NaN, different for 0.0 and -0.0."
  [x]
  (Double/doubleToLongBits (double x)))

(defn- atan2-of [[y x]] (array/atan2 y x))

(deftest elementary-functions-against-numpy
  (let [unary (for [[k f] elementary] [k (fn [[x]] (f x)) (mapv (fn [[x v]] [[x] v]) (fixtures k))])
        cases (conj (vec unary) [:atan2 atan2-of (mapv (fn [[y x v]] [[y x] v]) (fixtures :atan2))])]
    (testing "host scalars: within an ulp or two of numpy's, zeros with its sign"
      (doseq [[k f pts] cases
              [args expected] pts]
        (is (<= (error (f args) expected) 1e-15) (str (name k) " at " args))
        (when (zero? expected)
          (is (= (bits expected) (bits (f args))) (str (name k) " at " args ": the sign of zero")))))
    (testing "arrays give the host values: bit for bit on the JVM backend, within a few ulps on others"
      (doseq [[k f pts] cases]
        (let [columns (apply mapv vector (map first pts))
              got (f (mapv array/array columns))]
          (if (ts/jvm?)
            (is (= (mapv (comp bits f first) pts) (mapv bits (array/->clj got))) (name k))
            ;; on float32, against the host at the rounded inputs (unchecked:
            ;; float refuses the infinities)
            (let [rounded (mapv (fn [[args]] (mapv #(if (ts/f32?) (double (unchecked-float %)) %) args)) pts)
                  want (mapv f rounded)]
              (is (ts/close? (array/array want {:dtype (ts/float-dtype)}) got
                             (assoc (if (ts/f32?) {:rtol 1e-5 :atol 1e-6} {:rtol 1e-13 :atol 1e-14}) :equal-nan? true))
                  (name k))
              (is (= (mapv bits (filter zero? want)) (mapv bits (keep-indexed #(when (zero? (want %1)) %2) (array/->clj got))))
                  (str (name k) ": the signs of zeros")))))))))

(deftest lgamma-and-digamma-at-the-edges-as-scipy
  ;; the infinities, NaN and the poles, on the host and in arrays, against
  ;; scipy (generate.py's edges). lgamma(+Inf) was NaN on both paths, the
  ;; Lanczos sum's Inf·Inf - Inf (genclj-9gyi). Planted (2026-10-22): the
  ;; composite's +Inf case removed fails the arrays, the host path's the
  ;; host values. Not here, waiting for the owner: gammaln(-inf), which
  ;; scipy gives as -inf and gen.clj as +Inf, and psi(-0.0), +inf against -Inf
  (let [same? (fn [a b] (or (and (Double/isNaN a) (Double/isNaN b)) (== a b)))]
    (doseq [[k f] [[:lgamma-edges array/lgamma] [:digamma-edges array/digamma]]
            [x expected] (fixtures k)]
      (is (same? expected (double (f x))) (str (name k) " at " x " on the host"))
      (is (same? expected (double (array/item (f (array/array [x]))))) (str (name k) " at " x " in an array")))))

(deftest edge-cases
  (is (= ##Inf (array/erfinv 1.0)))
  (is (= ##-Inf (array/erfinv -1.0)))
  (is (Double/isNaN (array/erfinv 1.5)))
  (is (= 0.0 (array/erfinv 0.0)))
  (is (= 1.0 (array/erf ##Inf)))
  (is (= -1.0 (array/erf ##-Inf)))
  (is (= ##Inf (array/lgamma 0.0)) "lgamma has poles at the non-positive integers")
  (is (= ##Inf (array/lgamma -3.0)))
  (is (= ##-Inf (array/digamma 0.0)))
  (is (Double/isNaN (array/digamma -2.0)))
  (is (< (Math/abs (array/lgamma 1.0)) 1e-15))
  (is (< (Math/abs (array/lgamma 2.0)) 1e-15)))

(deftest identities
  (testing "erf inverts erfinv (the well-conditioned direction)"
    (doseq [y [-0.999999 -0.5 1e-12 0.1 0.9 0.99999999]]
      (is (< (error (array/erf (array/erfinv y)) y) 1e-15))))
  (testing "log B(a, b) = log Γ(a) + log Γ(b) - log Γ(a + b), and B(1, 1) = 1"
    (is (< (Math/abs (array/log-beta 1.0 1.0)) 1e-15))
    (is (< (error (array/log-beta 2.5 4.0) (- (+ (array/lgamma 2.5) (array/lgamma 4.0)) (array/lgamma 6.5))) 1e-15)))
  (testing "ψ(x + 1) = ψ(x) + 1/x"
    (doseq [x [0.3 1.7 12.5]]
      (is (< (error (array/digamma (+ x 1)) (+ (array/digamma x) (/ 1.0 x))) 1e-13)))))
