(ns build
  "Build tasks (clojure -T:build <task>).

   java  compiles the Java bindings in src-java/ into target/classes, which
         deps.edn puts on the classpath: mlx-c's (gen.mlx, generated by
         native/bindgen.clj), for the MLX backend, and llama.cpp's
         (gen.llama, generated by native/jextract-llama.sh), for the
         llama.cpp engine (gen.llm.llama). Each loads its native library
         only when used."
  (:require [clojure.tools.build.api :as b]))

(def class-dir "target/classes")

(defn java [_]
  (b/javac {:src-dirs ["src-java"]
            :class-dir class-dir
            :basis (b/create-basis {:project "deps.edn"})
            :javac-opts ["--release" "25" "-Xlint:all,-restricted" "-Werror"]})
  (println "compiled src-java into" class-dir))
