(ns build
  "Build tasks (clojure -T:build <task>).

   java  compiles the Java binding of mlx-c (src-java/, generated by
         native/bindgen.clj) into target/classes, which deps.edn puts on the
         classpath. Only the MLX backend needs it."
  (:require [clojure.tools.build.api :as b]))

(def class-dir "target/classes")

(defn java [_]
  (b/javac {:src-dirs ["src-java"]
            :class-dir class-dir
            :basis (b/create-basis {:project "deps.edn"})
            :javac-opts ["--release" "25" "-Xlint:all,-restricted" "-Werror"]})
  (println "compiled src-java into" class-dir))
